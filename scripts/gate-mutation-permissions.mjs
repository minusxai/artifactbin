import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {createEditableTableFixture} from './lib/editable-table-fixture.mjs';
import {startDocument,becomeOwner} from './lib/start-doc.mjs';
import {startMailSink,loginViaEmail} from './lib/mail-login.mjs';
const base=process.argv[2] ?? 'http://localhost:3060';
const fixture=await createEditableTableFixture(base,2,{seed:await startDocument(base)});
const browser=await chromium.launch();const sink=await startMailSink();
try {
 const owner=await browser.newPage();await becomeOwner(owner,base,fixture.token);
 const guest=await browser.newPage();await guest.goto(fixture.url);
 await guest.getByLabel('Item 1',{exact:true}).waitFor();
 assert.equal(await guest.getByLabel('Item 1',{exact:true}).isDisabled(),true);
 const forged=await guest.request.post(`${fixture.url}/mutate`,{data:{mutation:'set_item',values:{_value:'forged'},row:{id:1,item:'Task 1',owner:'TBD',hours:2,depends_on:'[]',tags:'[]',status:'backlog',sprint:''}}});
 assert.equal(forged.status(),403);
 const friend=await browser.newPage();const email=`mxmx_test_dataset_friend_${Date.now()}@example.com`;
 await loginViaEmail(friend,base,sink,email);
 await friend.goto(fixture.url);await friend.locator('iframe[title="artifact"]').waitFor();
 const frame=friend.frameLocator('iframe[title="artifact"]');
 await frame.getByLabel('Item 1',{exact:true}).waitFor();
 assert.equal(await frame.getByLabel('Item 1',{exact:true}).isDisabled(),true);
 const share=async patch=>{const r=await owner.request.put(`${base}/api/my/artifacts/${fixture.datasetId}/sharing`,{data:patch});assert.equal(r.status(),200,await r.text());};
 await share({shares:[{email,role:'editor'}]});
 await frame.locator('[aria-label="Item 1"]:enabled').waitFor();
 await frame.getByLabel('Item 1',{exact:true}).fill('Shared edit');await frame.getByLabel('Item 1',{exact:true}).press('Enter');
 await guest.waitForFunction(()=>document.querySelector('[aria-label="Item 1"]')?.value==='Shared edit');
 assert.equal(await guest.getByLabel('Item 1',{exact:true}).isDisabled(),true);
 await frame.getByLabel('Item 2',{exact:true}).fill('Unsaved draft');
 await share({shares:[{email,role:'viewer'}]});
 await frame.locator('[aria-label="Item 2"]:disabled').waitFor();
 assert.equal(await frame.getByLabel('Item 2',{exact:true}).inputValue(),'Unsaved draft');
 await share({shares:[{email,role:'editor'}]});
 await frame.locator('[aria-label="Item 2"]:enabled').waitFor();
 await share({access:'read'});
 await frame.locator('[aria-label="Item 2"]:disabled').waitFor();
 await frame.getByLabel('Filter status',{exact:true}).click();
 await frame.getByRole('option',{name:'backlog',exact:true}).click();
 console.log(`all good: anonymous refusal, shared editor, live grant/revoke, preserved draft, read-only live updates and filters: ${fixture.url}`);
}finally{await browser.close();await sink.close();}
