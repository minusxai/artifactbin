/**
 * Bundle src/af-script/{add,check,shot,publish,comments,auth,secrets}.ts (with the page model and parse5)
 * into skills/pagegi-author/scripts/: small entry scripts and one shared
 * module, lib/af-lib.mjs. Every entry imports only main.ts, so code splitting
 * yields exactly that one chunk. The only other imports are node: built-ins.
 * The output is committed; rebuild after changing either source.
 */
import { chmod, mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const outdir = join(root, "skills/pagegi-author/scripts");
const scripts = ["add", "check", "shot", "publish", "comments", "auth", "secrets"];
const note = "// Generated by `npm run build:af` from src/af-script/ and src/page/. Do not edit; needs Node.js 20.10+.\n";

const result = await build({
  absWorkingDir: root,
  entryPoints: Object.fromEntries(scripts.map((name) => [name, `src/af-script/${name}.ts`])),
  outdir,
  outExtension: { ".js": ".mjs" },
  chunkNames: "lib/af-lib",
  splitting: true,
  bundle: true,
  write: false,
  platform: "node",
  format: "esm",
  target: "node20.10",
  charset: "utf8",
  legalComments: "inline",
  logLevel: "warning",
});

const expected = [...scripts.map((name) => `${name}.mjs`), "lib/af-lib.mjs"].sort();
const produced = result.outputFiles.map((file) => relative(outdir, file.path)).sort();
if (produced.join() !== expected.join()) throw Error(`Expected ${expected.join(", ")}; esbuild produced ${produced.join(", ")}.`);

await rm(outdir, { recursive: true, force: true });
for (const file of result.outputFiles) {
  const entry = !relative(outdir, file.path).startsWith("lib");
  await mkdir(dirname(file.path), { recursive: true });
  await writeFile(file.path, (entry ? "#!/usr/bin/env node\n" : "") + note + file.text);
  if (entry) await chmod(file.path, 0o755);
}
