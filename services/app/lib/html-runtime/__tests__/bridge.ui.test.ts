it('uses original frame RPC with explicit HTML anchors and never exposes credentials', async () => {
  vi.stubGlobal('__AF_RUNTIME_CONFIG__', { pageId: 'p1', revision: '3', backends: ['orders'], appOrigin: 'https://platform.example' });
  const runtime = await import('../browser-client');
  const events: Array<{ kind: string; [key: string]: unknown }> = [];
  const bridge = runtime.startFrameBridge({ win: window, post: (event) => events.push(event), attach: { kind: 'attach', id: 'p1', nodes: [], editId: '3', source: null } });
  document.body.innerHTML = '<p data-af-id="n1">Hello</p>';
  bridge.receive({ kind: 'send', command: { type: 'mx:selection-actions', edit: false, annotate: true } });
  const menu = new MouseEvent('contextmenu', { bubbles: true, cancelable: true });
  document.querySelector('p')!.dispatchEvent(menu);
  const action = events.find((item) => item.kind === 'event')?.event as { selection: { anchor: unknown }; nonce: string };
  expect(action.selection.anchor).toEqual({ kind: 'html-node', v: 1, revision: '3', nodeId: 'n1', quote: '' });
  expect(action.nonce).toBe((events[0] as { nonce?: string }).nonce);
  expect(menu.defaultPrevented).toBe(true);
  bridge.receive({ kind: 'restored', call: 9 });
  expect(events).toContainEqual({ kind: 'restored', call: 9, ok: true });
  bridge.dispose();
});
it('relays remote queries and emits explicit invalidation names without overwriting local state', async () => {
  const actualWindow = window;
  vi.stubGlobal('__AF_RUNTIME_CONFIG__', { pageId: 'p1', revision: '3', backends: ['orders'], bindings: { orders: 'dataset1' }, appOrigin: 'https://platform.example' });
  vi.stubGlobal('window', { parent: {} });
  const runtime = await import('../browser-client');
  const events: Array<{ kind: string; [key: string]: unknown }> = [];
  const query = runtime.client.query({ query: runtime.gql`{ orders { total } }` });
  expect(events).toHaveLength(0);
  const bridge = runtime.startFrameBridge({ win: actualWindow, post: (event) => events.push(event), attach: { kind: 'attach', id: 'p1', nodes: [], editId: '3', source: null } });
  await Promise.resolve();
  const fetch = events.find((event) => event.kind === 'fetch')!;
  expect(fetch.path).toBe('/api/artifacts/p1/graphql');
  expect(JSON.parse(fetch.body as string)).toMatchObject({ operation: 'query', variables: {} });
  bridge.receive({ kind: 'fetch-result', call: fetch.call as number, status: 200, headers: {}, body: JSON.stringify({ data: { orders: { total: 9 } } }) });
  expect((await query).data).toEqual({ orders: { total: 9 } });
  const invalidations: unknown[] = [];
  const subscription = runtime.onBackendChange((names) => invalidations.push(names));
  bridge.receive({ kind: 'send', command: { type: 'mx:data', datasets: ['dataset1', 'unrelated'] } });
  expect(invalidations).toEqual([['orders']]);
  subscription.unsubscribe();
  bridge.receive({ kind: 'send', command: { type: 'mx:data', datasets: ['dataset1'] } });
  expect(invalidations).toHaveLength(1);
  expect(() => runtime.client.watchQuery({ query: runtime.gql`{ orders { total } }` })).toThrow();
  bridge.dispose();
});
it('uses original select controls for block picks, breadcrumbs and escape', async () => {
  vi.stubGlobal('__AF_RUNTIME_CONFIG__', { pageId: 'p1', revision: '3', backends: [] });
  const { startFrameBridge } = await import('../browser-client');
  const events: Array<{ kind: string; [key: string]: unknown }> = [];
  const bridge = startFrameBridge({ win: window, post: (event) => events.push(event), attach: { kind: 'attach', id: 'p1', nodes: [], editId: '3', source: null } });
  document.body.innerHTML = '<main data-af-id="n1"><p data-af-id="n2">words</p></main>';
  bridge.receive({ kind: 'send', command: { type: 'mx:annotations', mode: 'on', pins: [], openId: null, hoverId: null, canComment: true, pick: 'select' } });
  expect(document.documentElement.style.cursor).toBe('crosshair');
  document.querySelector('p')!.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true }));
  const selections = () => events.filter((item) => item.kind === 'event').map((item) => item.event as { type: string; selection?: { anchor: { nodeId: string } } | null }).filter((event) => event.type === 'mx:selection');
  expect(selections().at(-1)?.selection?.anchor.nodeId).toBe('n2');
  bridge.receive({ kind: 'send', command: { type: 'mx:select', path: 'n1' } });
  expect(selections().at(-1)?.selection?.anchor.nodeId).toBe('n1');
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' }));
  expect(document.documentElement.style.cursor).not.toBe('crosshair');
  expect(selections().at(-1)?.selection).toBeNull();
  bridge.dispose();
});
