import {afterEach,expect,it,vi} from 'vitest';
import {htmlSelection} from '../../html-bridge/selection';
afterEach(()=>{document.body.innerHTML='';localStorage.clear();vi.unstubAllGlobals();vi.resetModules();});
it('captures opt-in UI state, restores before target layout, and returns the private view on close',async()=>{
 vi.stubGlobal('__AF_RUNTIME_CONFIG__',{pageId:'comment-view-test',revision:'1',backends:[]});
 document.body.innerHTML=`<script type="application/json" data-af="state" data-af-comment-version="one" data-af-comment-fields='["screen"]'>{"screen":"home","draft":"private"}</script><p data-af-id="target">Target</p>`;
 const runtime=await import('../browser-client');
 const query=runtime.gql`{screen draft}`;
 await runtime.client.updateQuery({query},()=>({screen:'detail',draft:'private'}));
 const saved=htmlSelection(window,document.querySelector('p'),'1');
 expect(saved?.viewState).toEqual({v:2,state:{$html:{version:'one',fields:{screen:'detail'}}}});
 await runtime.client.updateQuery({query},()=>({screen:'home',draft:'my new draft'}));
 const events:unknown[]=[];
 const bridge=runtime.startFrameBridge({win:window,post:event=>events.push(event),attach:{kind:'attach',id:'comment-view-test',nodes:[],editId:'1',source:null}});
 bridge.receive({kind:'send',command:{type:'mx:annotations',mode:'on',pins:[{id:'thread',path:'target',viewState:saved?.viewState}],openId:'thread',hoverId:null}});
 await vi.waitFor(async()=>expect((await runtime.client.query({query})).data).toEqual({screen:'detail',draft:'my new draft'}));
 expect(events).toContainEqual(expect.objectContaining({kind:'event',event:expect.objectContaining({type:'mx:annotation-layout',viewStateError:null})}));
 bridge.receive({kind:'send',command:{type:'mx:annotations',mode:'on',pins:[],openId:null,hoverId:null}});
 await vi.waitFor(async()=>expect((await runtime.client.query({query})).data).toEqual({screen:'home',draft:'my new draft'}));
 bridge.dispose();
});
