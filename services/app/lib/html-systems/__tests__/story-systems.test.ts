import { describe, expect, it } from 'vitest';
import { STORY_SYSTEMS, STORY_SYSTEM_NAMES, getStorySystem } from '../story-systems';
import { STORY_THEME_NAMES, resolveStoredStoryDesign, resolveStoryMode } from '../story-themes';
import { STORY_DESIGN_NAMES } from '@/lib/validation';

/** The shadcn contract every theme fills (story-themes.test pins the same list for themes). */
const CONTRACT = ['background', 'foreground', 'card', 'card-foreground', 'popover', 'popover-foreground', 'primary', 'primary-foreground', 'secondary', 'secondary-foreground', 'muted', 'muted-foreground', 'accent', 'accent-foreground', 'destructive', 'destructive-foreground', 'border', 'input', 'ring', 'chart-1', 'chart-2', 'chart-3', 'chart-4', 'chart-5'];

describe('STORY_SYSTEMS registry (generated by scripts/design-systems.mjs)', () => {
  it('is the thirteen, in roster order, disjoint from the six themes, one entry per name', () => {
    expect(STORY_SYSTEM_NAMES.length).toBe(13);
    expect(STORY_SYSTEMS.map((s) => s.name)).toEqual([...STORY_SYSTEM_NAMES]);
    for (const name of STORY_SYSTEM_NAMES) expect(STORY_THEME_NAMES).not.toContain(name);
    expect(STORY_DESIGN_NAMES).toEqual([...STORY_THEME_NAMES, ...STORY_SYSTEM_NAMES]);
    // The registry reaches the browser through story-themes; the sheets (half a megabyte) stay in their own file.
    expect(JSON.stringify(STORY_SYSTEMS)).not.toContain('@font-face');
    expect(JSON.stringify(STORY_SYSTEMS)).not.toContain('.t-label');
  });

  it('every system fills the full contract in both modes, with radius and the three font stacks on the light side', () => {
    for (const s of STORY_SYSTEMS) {
      for (const key of CONTRACT) {
        expect(s.cssVars[`--${key}`], `${s.name} light --${key}`).toMatch(/^var\(--ds-[a-z0-9-]+\)$/);
        expect(s.darkCssVars[`--${key}`], `${s.name} dark --${key}`).toMatch(/^var\(--ds-[a-z0-9-]+\)$/);
      }
      for (const v of ['--radius', '--font-display', '--font-body', '--font-mono']) expect(s.cssVars[v], `${s.name} ${v}`).toBeTruthy();
      expect(['light', 'dark']).toContain(s.defaultMode);
      expect(s.label.length).toBeGreaterThan(0);
      expect(s.description.length).toBeGreaterThan(0);
    }
  });

  it('getStorySystem and storySystemSheetCss answer systems only', () => {
    expect(getStorySystem('volta')?.label).toBe('Volta');
    expect(getStorySystem('modernist')).toBeUndefined();
    expect(getStorySystem(null)).toBeUndefined();
  });
});

describe('a system is a theme to the fence, the emitter and the resolution', () => {
  it('a stored system name resolves to itself, with its declared default mode', () => {
    expect(resolveStoredStoryDesign('volta', null)).toEqual({ theme: 'volta', colorMode: null });
    expect(resolveStoredStoryDesign('phosphor', 'light')).toEqual({ theme: 'phosphor', colorMode: 'light' });
    expect(resolveStoryMode('phosphor', null)).toBe('dark');
    expect(resolveStoryMode('volta', null)).toBe('light');
    expect(resolveStoryMode('volta', 'dark')).toBe('dark');
  });

});
