import * as Y from 'yjs';
import {openRegionDoc} from '@/lib/live-regions';
import {expect,it} from 'vitest';
import {createArtifact,migrateLegacyPage,revertArtifactFor} from '@/lib/artifacts';
import {createUser,identityForUser} from '@/lib/accounts';
import {editableRegions} from '@/lib/live-regions';
import {useAppHarness,mintAccountToken,request} from './harness';
import {GET as read,PUT as replace} from '@/app/api/artifacts/[id]/route';
const harness=useAppHarness();
it('restores a legacy archive into native editing without rewriting the archive',async()=>{
 const user=await createUser({email:'mxmx_test_restore_native@example.com'});
 const row=await createArtifact(null,user.id,{format:'html',source:'<article data-af-editable="rich"><p>Original</p></article>',meta:{},visibility:'private'});
 await migrateLegacyPage(row.id,{apply:true});
 const db=await harness.db();
 const before=(await db.query('SELECT source FROM artifact_versions WHERE artifact_id=$1 AND version=$2',[row.id,row.version])).rows;
 const restored=await revertArtifactFor(identityForUser(user.id),row.id,row.version);
 expect(restored).toBeTruthy();
 const current=(await db.query<{source:string}>('SELECT source FROM artifacts WHERE id=$1',[row.id])).rows[0]!;
 expect(editableRegions(current.source).map(region=>region.kind)).toEqual(['rich-native-v1']);
 expect((await db.query('SELECT source FROM artifact_versions WHERE artifact_id=$1 AND version=$2',[row.id,row.version])).rows).toEqual(before);
});
it('normalizes migrated publications, refuses text, and preserves stale writer conflicts',async()=>{
 const {replaceArtifactFor,isVersionConflict}=await import('@/lib/artifacts');
 const user=await createUser({email:'mxmx_test_restore_write@example.com'}),actor=identityForUser(user.id);
 const row=await createArtifact(null,user.id,{format:'html',source:'<article data-af-editable="rich"><p>Original</p></article>',meta:{},visibility:'private'});
 await migrateLegacyPage(row.id,{apply:true});
 const db=await harness.db();
 const head=async()=>(await db.query<{source:string;version:number}>('SELECT source,version FROM artifacts WHERE id=$1',[row.id])).rows[0]!;
 const native=await head();
 expect(isVersionConflict(await replaceArtifactFor(actor,row.id,{format:'html',source:row.source,meta:{}},{expectedVersion:row.version}))).toBe(true);
 const refused=await replaceArtifactFor(actor,row.id,{format:'html',source:native.source.replace('rich-native-v1','text'),meta:{}},{expectedVersion:native.version});
 expect(refused).toBeInstanceOf(Response);
 expect((refused as Response).status).toBe(409);
 expect(await head()).toEqual(native);
 await replaceArtifactFor(actor,row.id,{format:'html',source:native.source.replace('rich-native-v1','rich').replace('Original','Changed'),meta:{}},{expectedVersion:native.version});
 const changed=await head();
 expect(editableRegions(changed.source).map(region=>region.kind)).toEqual(['rich-native-v1']);
 expect(changed.source).toContain('Changed');
 await replaceArtifactFor(actor,row.id,{format:'html',source:changed.source.replace('Changed','Fresh'),meta:{}},{expectedVersion:changed.version});
 expect((await head()).source).toContain('Fresh');
});
it('refuses an incompatible archived restore without modifying persisted state',async()=>{
 const user=await createUser({email:'mxmx_test_restore_refusal@example.com'});
 const row=await createArtifact(null,user.id,{format:'html',source:'<article data-af-editable="rich"><p>Original</p></article>',meta:{},visibility:'private'});
 await migrateLegacyPage(row.id,{apply:true});
 const db=await harness.db();
 await db.query("UPDATE artifact_versions SET source=replace(source,'editable=\"rich\"','editable=\"text\"') WHERE artifact_id=$1",[row.id]);
 const state=async()=>{
  const result=[];
  for(const table of ['artifacts','artifact_versions','region_states','region_snapshots','artifact_source_ids','annotations'])result.push((await db.query(`SELECT to_jsonb(t) AS value FROM ${table} t WHERE ${table==='artifacts'?'id':'artifact_id'}=$1`,[row.id])).rows);
  return result;
 };
 const stored=(await db.query<{region_id:string;state:Uint8Array}>('SELECT region_id,state FROM region_states WHERE artifact_id=$1',[row.id])).rows[0]!;
 const doc=openRegionDoc(stored.state,{kind:'rich-native-v1',clientId:12345});
 ((doc.getXmlFragment('native-v1').get(0) as Y.XmlElement).get(0) as Y.XmlText).insert(0,'Dirty ');
 await db.query('UPDATE region_states SET state=$2,dirty_since=clock_timestamp(),last_seq=1,state_seq=1 WHERE artifact_id=$1',[row.id,Buffer.from(Y.encodeStateAsUpdate(doc))]);
 doc.destroy();
 const before=await state();
 const result=await revertArtifactFor(identityForUser(user.id),row.id,row.version);
 expect(result).toHaveProperty('notArchived',true);
 expect(await state()).toEqual(before);
 await db.query("UPDATE artifact_versions SET source=replace(source,'editable=\"text\"','editable=\"rich\"') WHERE artifact_id=$1",[row.id]);
 await revertArtifactFor(identityForUser(user.id),row.id,row.version);
 const checkpoints=(await db.query<{source:string}>('SELECT source FROM artifact_versions WHERE artifact_id=$1',[row.id])).rows;
 expect(checkpoints.some(checkpoint=>checkpoint.source.includes('Dirty '))).toBe(true);
});

it('guards authenticated HTTP agent writes with both version and state conditions',async()=>{
 const account=await mintAccountToken('mxmx_test_migration_http');
 const row=await createArtifact(null,account.userId!,{format:'html',source:'<article data-af-editable="rich"><p>Original</p></article>',meta:{},visibility:'private'});
 const path=`/api/artifacts/${row.id}`,params={params:Promise.resolve({id:row.id})};
 const before=await (await read(request(path,{token:account.token}),params)).json();
 await migrateLegacyPage(row.id,{apply:true});
 const head=await (await read(request(path,{token:account.token}),params)).json();
 const send=(body:unknown)=>replace(request(path,{method:'PUT',token:account.token,json:body}),params);
 const legacy=head.html.replace('rich-native-v1','rich');
 expect((await send({html:legacy,expectedVersion:before.version,expectedState:before.state})).status).toBe(409);
 expect((await send({html:legacy,expectedVersion:head.version,expectedState:before.state})).status).toBe(409);
 const accepted=await send({html:legacy.replace('Original','Agent change'),expectedVersion:head.version,expectedState:head.state});
 expect(accepted.status).toBe(200);
 const current=await (await read(request(path,{token:account.token}),params)).json();
 expect(editableRegions(current.html).map(region=>region.kind)).toEqual(['rich-native-v1']);
 expect(current.html).toContain('Agent change');
});
