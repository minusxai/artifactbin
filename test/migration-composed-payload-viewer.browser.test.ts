// @requires archived-compiler
import { test } from "node:test";
import assert from "node:assert/strict";
import { createServer } from "node:http";
import { mkdtemp, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";
import { chromium } from "playwright";
import { compileArchivedLocal } from "../src/migration/conversion/compiled/local.ts";
import { externalCompile } from "../src/migration/conversion/compiled/index.ts";
import type { ArchivedLocalOutput } from "../src/migration/conversion/compiled/local-contracts.ts";
import { rewriteMigrationLinks } from "../src/migration/links.ts";
import { toPortable } from "../src/page/page-model.ts";
const root = process.env.PAGEGI_ARCHIVED_COMPILER_ROOT;

test(
  "compressed compiled reader preserves Context and gates pending, revoked and portable identity",
  { skip: !root },
  async () => {
    const result = await compileArchivedLocal(
      {
        source:
          '<Helmet><Context src="ref:Cx1234"/><Query name="readerId">{`select id from _me`}</Query></Helmet>{$_me.id ? <p id="reader">Reader</p> : <p id="guest">Guest</p>}<p id="subject">{$readerId.id}</p>',
        coreUrl: "/af/v1/core.js",
        viewerBinding: {
          backendNamespace: "legacyData",
          backendHref: "/af/v1/ids/Bk1234",
        },
      },
      {
        compiler: {
          compile: async (input) => {
            const output = (await externalCompile(
              input,
              { legacyRoot: root! },
              "./local-runner.mts",
            )) as ArchivedLocalOutput;
            // Keep the real compiled graph and admission path; inert generated bytes force
            // the same packaging boundary as an oversized archived runtime.
            return {
              ...output,
              javascript:
                output.javascript +
                "\nconst codecFixturePadding=" +
                JSON.stringify("x".repeat(4_000_000)) +
                ";",
            };
          },
        },
      },
    );
    assert.equal(
      result.classification,
      "functional",
      JSON.stringify(result.issues),
    );
    assert.ok(result.html);
    assert.match(result.html, /data-af-compiled-payload/);
    assert.ok(Buffer.byteLength(result.html) < 4_000_000);
    assert.deepEqual(result.provenance?.contexts, [{ legacyId: "Cx1234" }]);
    const html = rewriteMigrationLinks(
      result.html,
      { pages: { Cx1234: "Cx5678" }, users: {}, groups: {}, tokens: {} },
      {
        legacyOrigins: ["https://legacy.example"],
        targetOrigin: "https://pages.example",
        readyPages: new Set(["Cx5678"]),
      },
    );
    const core = (
      await build({
        entryPoints: ["src/browser/core/core.ts"],
        bundle: true,
        write: false,
        format: "iife",
        target: "es2022",
        minify: true,
        legalComments: "none",
      })
    ).outputFiles[0]!.text;
    const state = JSON.parse(
      /<script[^>]*data-af="state"[^>]*>([\s\S]*?)<\/script>/.exec(html)![1]!,
    );
    const portable = toPortable(html, {
      core,
      designSystem: "riso",
      designSystemCss: "",
      state,
    });
    assert.match(portable, /data-af-compiled-payload/);
    assert.match(portable, /href="\/a\/Cx5678"/);
    const directory = await mkdtemp(join(tmpdir(), "composed-reader-")),
      file = join(directory, "proof.html");
    await writeFile(file, portable);
    const csp =
      "default-src 'none'; script-src 'self' 'unsafe-inline' blob: 'wasm-unsafe-eval'; style-src 'unsafe-inline' data:; font-src data:; img-src data: blob:; connect-src 'none'; worker-src blob:";
    const server = createServer((request, response) =>
      response
        .writeHead(200, {
          "content-type":
            request.url === "/af/v1/core.js" ? "text/javascript" : "text/html",
          "Content-Security-Policy": csp,
        })
        .end(request.url === "/af/v1/core.js" ? core : html),
    );
    await new Promise<void>((resolve) =>
      server.listen(0, "127.0.0.1", resolve),
    );
    const browser = await chromium.launch();
    try {
      for (const mode of ["hosted", "portable"]) {
        const page = await browser.newPage();
        page.setDefaultTimeout(15000);
        const errors: string[] = [],
          external: string[] = [];
        page.on("pageerror", (error) => errors.push(error.message));
        await page.route(/^https?:/, (route) => {
          const url = new URL(route.request().url());
          if (mode === "portable" || url.hostname !== "127.0.0.1") {
            external.push(url.origin);
            return route.abort();
          }
          return route.continue();
        });
        await page.addInitScript(`{
        const w=window,listeners=new Set();w.__jobs=[];
        w.__invalidate=()=>{for(const listener of listeners)listener();};
        w.__answer=(id,error=false)=>{const resolve=w.__jobs.shift();if(!resolve)throw Error("No held reader request");resolve(error?{data:null,errors:[{message:"Unavailable"}]}:{data:{legacyData:{viewer:{generation:(id===null?"b":"a").repeat(64),id}}}});};
        w[Symbol.for("afbin.host")]={viewer:()=>({dark:null,designSystem:null}),subscribeViewer:()=>()=>{},state:()=>null,remote:()=>({online:()=>true,authorizationContext:()=>null,subscribe:(listener)=>{listeners.add(listener);return()=>listeners.delete(listener);},execute:()=>new Promise(resolve=>w.__jobs.push(resolve))})};
      }`);
        await page.goto(
          mode === "portable"
            ? pathToFileURL(file).href
            : `http://127.0.0.1:${(server.address() as { port: number }).port}/proof`,
        );
        const gate = page.locator("[data-migration-viewer-content]");
        await page
          .waitForFunction(() => (window as any).__jobs.length === 1)
          .catch(() => {
            throw Error(
              JSON.stringify({ mode, errors, phase: "initial-request" }),
            );
          });
        assert.equal(
          await page.locator("[data-af-compiled-payload]").count(),
          1,
        );
        assert.equal(await gate.isVisible(), false);
        assert.equal(
          await gate.evaluate((node) => (node as HTMLElement).inert),
          true,
        );
        assert.equal(
          await page
            .locator('link[rel="related"][data-migration-context]')
            .getAttribute("href"),
          "/a/Cx5678",
        );
        await page.evaluate(() => (window as any).__answer("reader-one"));
        await page.locator("#reader").waitFor({ state: "visible" });
        assert.equal(await page.locator("#subject").innerText(), "reader-one");
        assert.equal(await page.locator("#guest").count(), 0);
        await page.evaluate(() => {
          (window as any).__invalidate();
          const gate = document.querySelector<HTMLElement>(
            "[data-migration-viewer-content]",
          );
          if (!gate?.hidden || !gate.inert)
            throw Error("Revocation did not synchronously gate content");
        });
        await page.waitForFunction(() => (window as any).__jobs.length === 1);
        await page.evaluate(() => (window as any).__answer(null, true));
        await page.waitForFunction(() =>
          document
            .querySelector("[data-migration-viewer-status]")
            ?.textContent?.includes("unavailable"),
        );
        assert.equal(await gate.isVisible(), false);
        assert.equal(await page.locator("#guest").isVisible(), false);
        await page.reload();
        await page.waitForFunction(() => (window as any).__jobs.length === 1);
        assert.equal(await gate.isVisible(), false);
        await page.evaluate(() => (window as any).__answer(null));
        await page.locator("#guest").waitFor({ state: "visible" });
        assert.equal(
          await gate.evaluate((node) => (node as HTMLElement).inert),
          false,
        );
        assert.deepEqual(errors, []);
        assert.deepEqual(external, []);
        await page.close();
      }
    } finally {
      await browser.close();
      server.closeAllConnections();
      await new Promise<void>((resolve) => server.close(() => resolve()));
      await rm(directory, { recursive: true, force: true });
    }
  },
);
